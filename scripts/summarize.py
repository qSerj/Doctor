#!/usr/bin/env python3
"""Оснастка стенда — сводка по пачке отчётов доктора.

Читает `reports.jsonl` и `index.tsv`, оставленные `run-batch.sh`, и кладёт рядом:

* `сводка.md` — проекты названы номерами, имён клиентских работ в ней нет;
* `гнёзда.tsv` — номер гнезда против настоящего пути, только для закрытой памяти;
* `находки.tsv` — срабатывания правил числами, сырьё для калибровки порогов.

Единица разбора — файл, единица статистики — гнездо (каталог). У каждого
распределения в сводке стоит пометка, по чему оно посчитано.
"""

import json
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ПРАВИЛА = [
    "oversized-stills",
    "zoom-exceeds-pixels",
    "oversized-video",
    "unresolved-paths",
    "foreign-root",
    "audio-longer-than-show",
]


def прочитать(каталог):
    отчёты = []
    with (каталог / "reports.jsonl").open(encoding="utf-8") as f:
        for строка in f:
            строка = строка.strip()
            if строка:
                отчёты.append(json.loads(строка))

    указатель = []
    with (каталог / "index.tsv").open(encoding="utf-8") as f:
        next(f)
        for строка in f:
            n, код, мс, байт, путь = строка.rstrip("\n").split("\t", 4)
            указатель.append(
                {"n": int(n), "код": int(код), "мс": int(мс), "байт": int(байт), "путь": путь}
            )
    return отчёты, указатель


def число(таблица):
    """Строка «мин — медиана — макс» по списку чисел."""
    if not таблица:
        return "—"
    return f"{min(таблица)} — {int(statistics.median(таблица))} — {max(таблица)}"


def главное(отчёт):
    """Ключевые числа одного файла: то, по чему сравниваются файлы внутри гнезда."""
    инв = отчёт.get("inventory") or {}
    слайды = инв.get("slides") or {}
    медиа = инв.get("media") or {}
    шапка = отчёт.get("header") or {}
    return {
        "версия": шапка.get("proshowMajorVersion") or ("нет:" + str(шапка.get("proshowVersion"))),
        "слайдов": слайды.get("parsedCount") or 0,
        "длительностьМс": слайды.get("totalTimeMs") or 0,
        "пикселейБайт": медиа.get("unpackedBytes") or 0,
        "слоёв": (инв.get("layers") or {}).get("totalCount") or 0,
        "медиаУникальных": медиа.get("uniqueCount") or 0,
    }


def main():
    каталог = Path(sys.argv[1])
    отчёты, указатель = прочитать(каталог)
    мета_путь = каталог / "run-meta.json"
    мета = json.loads(мета_путь.read_text(encoding="utf-8")) if мета_путь.exists() else {}
    if len(отчёты) != len(указатель):
        print(f"Строк отчёта {len(отчёты)}, строк указателя {len(указатель)} — расходятся", file=sys.stderr)
        return 3

    for о, и in zip(отчёты, указатель):
        о["_и"] = и
        о["_главное"] = главное(о)
        о["_гнездо"] = str(Path(и["путь"]).parent)

    # Гнёзда нумеруются по порядку появления: номер устойчив, пока каталог не менялся.
    гнёзда = {}
    for о in отчёты:
        гнёзда.setdefault(о["_гнездо"], []).append(о)
    номер = {г: i + 1 for i, г in enumerate(sorted(гнёзда))}

    (каталог / "гнёзда.tsv").write_text(
        "номер\tфайлов\tпуть\n"
        + "".join(f"{номер[г]}\t{len(гнёзда[г])}\t{г}\n" for г in sorted(гнёзда)),
        encoding="utf-8",
    )

    строки = []
    д = строки.append

    разобрано = [о for о in отчёты if (о.get("source") or {}).get("magicMatched")]
    сбои = [о for о in отчёты if о["_и"]["код"] not in (0, 1)]
    с_проблемами = [о for о in отчёты if (о.get("parse") or {}).get("problemCount", 0) > 0]
    с_противоречиями = [
        о
        for о in с_проблемами
        if any(p["kind"] != "RepeatedKey" for p in (о["parse"]["problems"] or []))
    ]
    время = sum(о["_и"]["мс"] for о in отчёты) / 1000
    первые_десять = sum(о["_и"]["мс"] for о in отчёты[:10]) / 1000
    оценка_по_десяти = первые_десять * len(отчёты) / min(10, len(отчёты))

    д("# Сводка прогона по пачке")
    д("")
    д("Проекты названы номерами гнёзд; соответствие номеров настоящим путям — в `гнёзда.tsv`.")
    д("")
    д("| | |")
    д("| --- | --- |")
    д(f"| Файлов шоу | {len(отчёты)} |")
    д(f"| Гнёзд (каталогов) | {len(гнёзда)} |")
    д(f"| Разобрано (сигнатура совпала) | {len(разобрано)} |")
    д(f"| Не файл шоу или сбой чтения | {len(сбои)} |")
    д(f"| Файлов с замечаниями разбора | {len(с_проблемами)} |")
    д(f"| Из них с противоречиями или повреждением | {len(с_противоречиями)} |")
    д(f"| Оценка одного прохода CLI по первым десяти, с | {оценка_по_десяти:.1f} |")
    д(f"| Сумма времени одного прохода CLI, с | {время:.1f} |")
    if "wallSeconds" in мета:
        д(f"| Время команды целиком, включая обезличенный проход, с | {мета['wallSeconds']} |")
    д("")

    if сбои:
        д("## Файлы, которые не разобрались — поимённо")
        д("")
        for о in сбои:
            д(f"- гнездо {номер[о['_гнездо']]}, файл `{Path(о['_и']['путь']).name}`: код {о['_и']['код']}")
        д("")

    if с_проблемами:
        д("## Замечания разбора — по файлам")
        д("")
        for о in с_проблемами:
            виды = Counter(p["kind"] for p in (о["parse"]["problems"] or []))
            д(
                f"- гнездо {номер[о['_гнездо']]}, файл {о['_и']['n']}: "
                f"{о['parse']['problemCount']} шт — {dict(виды)}"
            )
        д("")

    # --- версии ---
    по_файлам = Counter(о["_главное"]["версия"] for о in отчёты)
    по_гнёздам = Counter()
    for г, фф in гнёзда.items():
        вв = {о["_главное"]["версия"] for о in фф}
        по_гнёздам["разнобой: " + "/".join(sorted(вв)) if len(вв) > 1 else вв.pop()] += 1

    д("## Версии программы")
    д("")
    д(f"| Версия | По файлам ({len(отчёты)} шт) | По гнёздам ({len(гнёзда)} шт) |")
    д("| --- | --- | --- |")
    for в in sorted(set(по_файлам) | set(по_гнёздам), key=lambda x: -по_файлам.get(x, 0)):
        д(f"| {в} | {по_файлам.get(в, 0)} | {по_гнёздам.get(в, 0)} |")
    д("")

    # --- словарь форм ---
    форма_файлов = Counter()
    форма_гнёзд = defaultdict(set)
    форма_известна = {}
    форма_всего = Counter()
    версии_формы = defaultdict(set)
    for о in отчёты:
        сл = о.get("dictionary") or {}
        for ш in сл.get("shapes") or []:
            форма_файлов[ш["shape"]] += 1
            форма_гнёзд[ш["shape"]].add(о["_гнездо"])
            форма_известна[ш["shape"]] = ш["known"]
            форма_всего[ш["shape"]] += ш["count"]
            версии_формы[ш["shape"]].add(о["_главное"]["версия"])

    известных = sum(1 for ш, з in форма_известна.items() if з)
    вхожд_изв = sum(форма_всего[ш] for ш, з in форма_известна.items() if з)
    вхожд_всего = sum(форма_всего.values())

    д("## Словарь форм ключей")
    д("")
    д("| | |")
    д("| --- | --- |")
    д(f"| Различных форм в пачке | {len(форма_известна)} |")
    д(f"| Из них доктор читает | {известных} ({известных * 100 // max(1, len(форма_известна))}%) |")
    д(f"| Вхождений ключей всего | {вхожд_всего} |")
    д(f"| Вхождений, попавших в модель | {вхожд_изв} ({вхожд_изв * 100 // max(1, вхожд_всего)}%) |")
    д(f"| Форм во всех {len(отчёты)} файлах сразу | {sum(1 for ш, c in форма_файлов.items() if c == len(отчёты))} |")
    д(f"| Форм ровно в одном файле | {sum(1 for c in форма_файлов.values() if c == 1)} |")
    д("")
    д("Двадцать самых частых форм, которых доктор не читает (по числу гнёзд):")
    д("")
    д("| Форма | Гнёзд | Файлов | Вхождений |")
    д("| --- | --- | --- | --- |")
    неизв = [ш for ш, з in форма_известна.items() if not з]
    for ш in sorted(неизв, key=lambda s: (-len(форма_гнёзд[s]), -форма_всего[s]))[:20]:
        д(f"| `{ш}` | {len(форма_гнёзд[ш])} | {форма_файлов[ш]} | {форма_всего[ш]} |")
    д("")

    новые_версии = {"8.0"} | {в for в in по_файлам if в.startswith("нет:")}
    только_новые = [ш for ш in форма_известна if версии_формы[ш] <= новые_версии]
    д(f"Формы, встреченные **только** в версиях {sorted(новые_версии)} (двор их не видел): {len(только_новые)} шт.")
    if только_новые:
        д("")
        for ш in sorted(только_новые, key=lambda s: -форма_всего[s])[:30]:
            д(f"- `{ш}` — {форма_всего[ш]} вхождений в {форма_файлов[ш]} файлах, доктор {'читает' if форма_известна[ш] else 'не читает'}")
    д("")

    # --- медиа ---
    опрошено = sum((о.get("inventory") or {}).get("media", {}).get("probedCount", 0) for о in отчёты)
    уникальных = sum((о.get("inventory") or {}).get("media", {}).get("uniqueCount", 0) for о in отчёты)
    по_статусу = Counter()
    непрочтённые = defaultdict(lambda: [0, 0])
    расширения = Counter()
    for о in отчёты:
        for i in ((о.get("inventory") or {}).get("media") or {}).get("items") or []:
            по_статусу[i["status"]] += 1
            расширения[i["extension"]] += 1
            if i["status"] in ("UnknownFormat", "BrokenHeader", "NotProbed", "Unreadable"):
                к = f"{i['extension']}/{i['status']}"
                непрочтённые[к][0] += 1
                непрочтённые[к][1] += i.get("fileBytes") or 0

    д("## Медиа")
    д("")
    д(f"Ссылок на уникальные файлы по пачке: {уникальных}; размер снят у {опрошено} ({опрошено * 100 // max(1, уникальных)}%). Посчитано по файлам шоу.")
    д("")
    д("| Исход опроса | Файлов |")
    д("| --- | --- |")
    for с, c in по_статусу.most_common():
        д(f"| {с} | {c} |")
    д("")
    д("Форматы, которые нынешние читалки не берут:")
    д("")
    д("| Расширение / исход | Файлов | Байт |")
    д("| --- | --- | --- |")
    for к, (c, b) in sorted(непрочтённые.items(), key=lambda kv: -kv[1][0]):
        д(f"| {к} | {c} | {b} |")
    д("")

    # --- правила ---
    срабатываний = Counter()
    файлов_с_правилом = Counter()
    гнёзд_с_правилом = defaultdict(set)
    for о in отчёты:
        свои = Counter(f["ruleId"] for f in о.get("findings") or [])
        for r, c in свои.items():
            срабатываний[r] += c
            файлов_с_правилом[r] += 1
            гнёзд_с_правилом[r].add(о["_гнездо"])

    д("## Шесть правил приёмки")
    д("")
    д("| Правило | Срабатываний | Файлов из %d | Гнёзд из %d |" % (len(отчёты), len(гнёзда)))
    д("| --- | --- | --- | --- |")
    for r in ПРАВИЛА:
        д(f"| `{r}` | {срабатываний.get(r, 0)} | {файлов_с_правилом.get(r, 0)} | {len(гнёзд_с_правилом.get(r, ()))} |")
    д("")

    with (каталог / "находки.tsv").open("w", encoding="utf-8") as f:
        поля = sorted({к for о in отчёты for нах in о.get("findings") or [] for к in нах["numbers"]})
        f.write("гнездо\tфайл\tправило\tадрес\t" + "\t".join(поля) + "\n")
        for о in отчёты:
            for нах in о.get("findings") or []:
                f.write(
                    f"{номер[о['_гнездо']]}\t{о['_и']['n']}\t{нах['ruleId']}\t{нах['address']['stableKey']}\t"
                    + "\t".join(str(нах["numbers"].get(к, "")) for к in поля)
                    + "\n"
                )

    # --- гнёзда с несколькими файлами ---
    многофайловые = {г: фф for г, фф in гнёзда.items() if len(фф) > 1}
    д(f"## Гнёзда с несколькими файлами: {len(многофайловые)} шт")
    д("")
    д("Разброс — отношение максимума к минимуму. Малый разброс — варианты одной работы,")
    д("большой — разные работы, оказавшиеся в одном каталоге. Что там на самом деле, решает Э2.2.")
    д("")
    д("| Гнездо | Файлов | Слайды (мин…макс) | Разброс слайдов | Пиксели, ГБ (мин…макс) | Разброс пикселей |")
    д("| --- | --- | --- | --- | --- | --- |")
    for г, фф in sorted(многофайловые.items(), key=lambda kv: -len(kv[1])):
        с = [о["_главное"]["слайдов"] for о in фф]
        п = [о["_главное"]["пикселейБайт"] for о in фф]
        рс = f"{max(с) / max(1, min(с)):.1f}×"
        рп = f"{max(п) / max(1, min(п)):.1f}×"
        д(
            f"| {номер[г]} | {len(фф)} | {min(с)}…{max(с)} | {рс} "
            f"| {min(п) / 2**30:.2f}…{max(п) / 2**30:.2f} | {рп} |"
        )
    д("")

    # --- распределения по гнёздам и выбросы ---
    def по_гнезду(ключ):
        """Гнездо даёт один голос: медиану своих файлов."""
        return {г: statistics.median(о["_главное"][ключ] for о in фф) for г, фф in гнёзда.items()}

    д(f"## Распределения (единица — гнездо, {len(гнёзда)} голосов)")
    д("")
    д("| Величина | мин | 25% | медиана | 75% | 90% | макс |")
    д("| --- | --- | --- | --- | --- | --- | --- |")
    выбросы = defaultdict(list)
    for ключ, имя, делитель in [
        ("слайдов", "Слайдов", 1),
        ("слоёв", "Слоёв", 1),
        ("медиаУникальных", "Уникальных медиа", 1),
        ("длительностьМс", "Длительность, с", 1000),
        ("пикселейБайт", "Распакованные пиксели, МБ", 2**20),
    ]:
        значения = sorted(по_гнезду(ключ).values())
        def кв(доля):
            return значения[min(len(значения) - 1, int(len(значения) * доля))] / делитель
        д(
            f"| {имя} | {значения[0] / делитель:.1f} | {кв(0.25):.1f} | {кв(0.5):.1f} "
            f"| {кв(0.75):.1f} | {кв(0.9):.1f} | {значения[-1] / делитель:.1f} |"
        )
        порог = кв(0.9) * делитель * 3
        for г, v in по_гнезду(ключ).items():
            if v > порог:
                выбросы[номер[г]].append(f"{имя}: {v / делитель:.1f}")

    д("")
    д("## Подозрительные проекты — очередь подопытных Э3.1")
    д("")
    д("Выброс здесь значит «доктор говорит про этот проект странное», а не «проект сломан».")
    д("Различить находку, сломанный проект и дыру в разборе можно только в самой программе.")
    д("")
    д("| Гнездо | Чем выделяется |")
    д("| --- | --- |")
    for о in сбои + с_противоречиями:
        выбросы[номер[о["_гнездо"]]].append("замечания разбора")
    for н in sorted(выбросы):
        д(f"| {н} | {'; '.join(sorted(set(выбросы[н])))} |")
    д("")

    (каталог / "сводка.md").write_text("\n".join(строки) + "\n", encoding="utf-8")
    print(f"Сводка: {каталог / 'сводка.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
